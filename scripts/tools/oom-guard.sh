#!/usr/bin/env bash
# =============================================================================
# oom-guard.sh - keep WezTerm and the KDE compositor out of systemd-oomd
#                candidacy, and contain a heavy AI/dev harness in its own
#                memory-capped slice
# =============================================================================
# Layered defence against systemd-oomd killing the terminal (see
# docs/OOM-WEZTERM.md). Everything is user-level: no root, no system units,
# no swap/zram/sysctl changes, systemd-oomd stays enabled.
#
#   L1 containment  harness.slice (MemoryHigh/Max) + harness-run.sh launcher
#   L2 immunity     ManagedOOMPreference=omit on WezTerm and the plasma units
#   L3 policy       systemd-oomd keeps its vendor kill@80% policy for the rest
#
# Usage:
#   ./scripts/tools/oom-guard.sh             install (idempotent, default)
#   ./scripts/tools/oom-guard.sh --dry-run   show what would change, change nothing
#   ./scripts/tools/oom-guard.sh --uninstall remove everything this script added
#   ./scripts/tools/oom-guard.sh --help
# =============================================================================
set -Eeuo pipefail

# --- tunables ---------------------------------------------------------------
# No MemoryHigh on purpose: a soft limit below the cap livelocks unreclaimable
# anon pages (allocations stall at MemoryHigh and never reach MemoryMax - measured
# during the containment test, 60s of no progress). One hard cap, one kill path.
MEMORY_MAX="18G"      # 58% of this machine's 30.9G RAM
MEMORY_SWAP_MAX="4G"  # zram-backed grace; prevents btrfs swapfile thrash
OOM_SCORE_ADJ="900"   # kernel-OOM victim priority, applied at scope creation
GUARD_INTERVAL="10s"  # must stay below oomd's 20s pressure duration
# ---------------------------------------------------------------------------

SYSTEMD_USER_DIR="$HOME/.config/systemd/user"
GUARD_LIB_DIR="$HOME/.local/lib/no-cowboy"
GUARD_RUN="$GUARD_LIB_DIR/oom-guard-run.sh"
LOCAL_BIN_DIR="$HOME/.local/bin"
SELF="$(readlink -f "${BASH_SOURCE[0]}")"
SELF_DIR="$(dirname "$SELF")"
LAUNCHER="$SELF_DIR/harness-run.sh"

PROTECTED_UNITS=(
    "plasma-kwin_wayland.service"
    "plasma-plasmashell.service"
    "plasma-kded6.service"
)

MODE="install"
DRY_RUN=false

say()  { printf '  %s\n' "$*"; }
warn() { printf '  WARNING: %s\n' "$*" >&2; }
fail() { printf 'FATAL: %s\n' "$*" >&2; exit 1; }

usage() {
    sed -n '15,19p' "$SELF" | sed 's/^# \{0,1\}//'
}

write_file() {
    local path="$1" content="$2"
    if [ -f "$path" ] && [ "$(cat "$path")" = "$content" ]; then
        say "unchanged: $path"
        return 0
    fi
    if $DRY_RUN; then
        say "[dry-run] write: $path"
        return 0
    fi
    mkdir -p "$(dirname "$path")"
    printf '%s\n' "$content" > "$path"
    say "wrote: $path"
}

remove_path() {
    local path="$1"
    if [ ! -e "$path" ] && [ ! -L "$path" ]; then
        say "absent: $path"
        return 0
    fi
    if $DRY_RUN; then
        say "[dry-run] remove: $path"
        return 0
    fi
    rm -f "$path"
    say "removed: $path"
}

run_cmd() {
    if $DRY_RUN; then
        say "[dry-run] $*"
        return 0
    fi
    "$@" || { warn "failed: $*"; return 1; }
}

guard_body() {
    cat <<'GUARD_BODY'
#!/usr/bin/env bash
# oom-guard-run.sh - mark the terminal and compositor cgroups as oomd "omit"
# Generated by scripts/tools/oom-guard.sh. Runs every 10s as a user timer:
# the WezTerm unit is transient and gets a fresh UUID at every launch, so its
# ManagedOOMPreference has to be re-applied; the plasma units are real units
# and carry persistent drop-ins, this is the immediate-apply path for them.
set -Eeuo pipefail

PROTECTED_UNITS=(
    plasma-kwin_wayland.service
    plasma-plasmashell.service
    plasma-kded6.service
)

protect() {
    local unit="$1" current
    current="$(systemctl --user show "$unit" -p ManagedOOMPreference --value 2>/dev/null || true)"
    [ -n "$current" ] || return 0          # vanished or never loaded
    [ "$current" = "omit" ] && return 0    # already protected
    systemctl --user set-property "$unit" ManagedOOMPreference=omit >/dev/null 2>&1 || true
}

# Dynamic: every WezTerm instance the KDE portal spawned.
while IFS= read -r unit; do
    [ -n "$unit" ] && protect "$unit"
done < <(systemctl --user list-units --type=service --no-legend --plain --no-pager \
             'app-org.wezfurlong.wezterm@*' 2>/dev/null | awk 'NF {print $1}')

# Static: compositor and workspace shell - killing either loses the session.
for unit in "${PROTECTED_UNITS[@]}"; do
    protect "$unit"
done

exit 0
GUARD_BODY
}

install_all() {
    echo "Installing the NoCowboy OOM guard (rootless)..."
    [ -x "$LAUNCHER" ] || fail "missing launcher: $LAUNCHER"

    write_file "$SYSTEMD_USER_DIR/harness.slice" "[Slice]
MemoryMax=${MEMORY_MAX}
MemorySwapMax=${MEMORY_SWAP_MAX}
ManagedOOMMemoryPressure=auto"

    # The vendor ships /usr/lib/systemd/user/slice.d/10-oomd-per-slice-defaults.conf
    # (kill@80%), and drop-ins always override the main unit file - including a
    # main file in ~/.config. An admin drop-in is what actually makes the
    # ceilings and "auto" effective (verified with systemctl show).
    write_file "$SYSTEMD_USER_DIR/harness.slice.d/zz-oom.conf" "[Slice]
MemoryMax=${MEMORY_MAX}
MemorySwapMax=${MEMORY_SWAP_MAX}
ManagedOOMMemoryPressure=auto"

    write_file "$SYSTEMD_USER_DIR/oom-guard.service" "[Unit]
Description=NoCowboy OOM guard - keep the terminal and compositor out of oomd candidacy

[Service]
Type=oneshot
ExecStart=%h/.local/lib/no-cowboy/oom-guard-run.sh"

    write_file "$SYSTEMD_USER_DIR/oom-guard.timer" "[Unit]
Description=NoCowboy OOM guard timer

[Timer]
OnBootSec=15s
OnUnitActiveSec=${GUARD_INTERVAL}
Unit=oom-guard.service

[Install]
WantedBy=timers.target"

    write_file "$GUARD_RUN" "$(guard_body)"

    local unit
    for unit in "${PROTECTED_UNITS[@]}"; do
        write_file "$SYSTEMD_USER_DIR/${unit}.d/zz-oom.conf" "[Service]
ManagedOOMPreference=omit"
    done

    if $DRY_RUN; then
        say "[dry-run] chmod 755 $GUARD_RUN"
        say "[dry-run] install $LAUNCHER -> $GUARD_LIB_DIR/harness-run.sh"
        say "[dry-run] ln -sfn $GUARD_LIB_DIR/harness-run.sh $LOCAL_BIN_DIR/harness"
    else
        chmod 755 "$GUARD_RUN"
        # The launcher must not live on a removable/external volume: the repo is
        # on an external drive, and a symlink into it silently dies on unmount.
        mkdir -p "$GUARD_LIB_DIR" "$LOCAL_BIN_DIR"
        install -m 755 "$LAUNCHER" "$GUARD_LIB_DIR/harness-run.sh"
        ln -sfn "$GUARD_LIB_DIR/harness-run.sh" "$LOCAL_BIN_DIR/harness"
        say "installed: $GUARD_LIB_DIR/harness-run.sh"
        say "linked:    $LOCAL_BIN_DIR/harness -> $GUARD_LIB_DIR/harness-run.sh"
    fi

    run_cmd systemctl --user daemon-reload || true
    run_cmd systemctl --user enable --now oom-guard.timer || true
    run_cmd systemctl --user restart oom-guard.service || true

    case ":$PATH:" in
        *":$LOCAL_BIN_DIR:"*) ;;
        *) warn "$LOCAL_BIN_DIR is not in PATH - call $LAUNCHER directly" ;;
    esac

    if ! $DRY_RUN; then
        echo "Effective slice limits:"
        systemctl --user show harness.slice \
            -p MemoryHigh -p MemoryMax -p MemorySwapMax \
            -p ManagedOOMMemoryPressure 2>/dev/null | sed 's/^/  /'
        say "harness scope: oom_score_adj=${OOM_SCORE_ADJ} (applied inside the scope)"
    fi

    echo "Done. Launch heavy work as:  harness <command>"
}

uninstall_all() {
    echo "Removing the NoCowboy OOM guard..."
    run_cmd systemctl --user disable --now oom-guard.timer || true
    run_cmd systemctl --user stop oom-guard.service || true
    run_cmd systemctl --user stop harness.slice || true

    remove_path "$SYSTEMD_USER_DIR/oom-guard.timer"
    remove_path "$SYSTEMD_USER_DIR/oom-guard.service"
    remove_path "$SYSTEMD_USER_DIR/harness.slice"
    remove_path "$SYSTEMD_USER_DIR/harness.slice.d/zz-oom.conf"
    remove_path "$GUARD_RUN"
    local unit
    for unit in "${PROTECTED_UNITS[@]}"; do
        remove_path "$SYSTEMD_USER_DIR/${unit}.d/zz-oom.conf"
    done
    remove_path "$LOCAL_BIN_DIR/harness"
    remove_path "$GUARD_LIB_DIR/harness-run.sh"

    run_cmd systemctl --user daemon-reload || true

    # Restore oomd candidacy on the live units (drop-ins only apply on reload).
    local current
    for unit in "${PROTECTED_UNITS[@]}"; do
        current="$(systemctl --user show "$unit" -p ManagedOOMPreference --value 2>/dev/null || true)"
        [ -n "$current" ] && run_cmd systemctl --user set-property "$unit" ManagedOOMPreference=none || true
    done
    while IFS= read -r unit; do
        [ -n "$unit" ] || continue
        run_cmd systemctl --user set-property "$unit" ManagedOOMPreference=none || true
    done < <(systemctl --user list-units --type=service --no-legend --plain --no-pager \
                 'app-org.wezfurlong.wezterm@*' 2>/dev/null | awk 'NF {print $1}')

    echo "Done. WezTerm and plasma are oomd candidates again."
}

for arg in "$@"; do
    case "$arg" in
        --install)   MODE="install" ;;
        --uninstall) MODE="uninstall" ;;
        --dry-run)   DRY_RUN=true ;;
        -h|--help)   usage; exit 0 ;;
        *)           printf 'unknown option: %s\n' "$arg" >&2; usage >&2; exit 2 ;;
    esac
done

[ "$EUID" -eq 0 ] && fail "run as your own user, not root (this design is rootless)"

case "$MODE" in
    install)   install_all ;;
    uninstall) uninstall_all ;;
esac
